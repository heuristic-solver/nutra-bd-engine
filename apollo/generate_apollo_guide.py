doc_lines.append("- **Hiring & Job Postings (`job_posting`):** Live job openings indexed across company career pages, title, department, location, date posted.")
doc_lines.append("- **Corporate News & Events (`news_article`):** Executive moves, product launches, funding announcements, M&A press releases categorized by tag and publication date.")
doc_lines.append("- **Intent & Technographics (`intent_topic` / `technology`):** High-intent surge topics and current active technologies used by accounts.\n")

doc_lines.append("### B. Workspace CRM & Engagement Database")
doc_lines.append("- **Accounts (`account`):** Accounts imported or tracked in the user's workspace, tied to sales reps (owners), pipeline stages (`account_stage`), and custom fields.")
doc_lines.append("- **Contacts (`contact`):** People imported into the workspace CRM with contact stages (`contact_stage`), ownership permissions, sequence enrollment history, and deal associations.")
doc_lines.append("- **Sequences (`emailer_campaign`):** Multi-step outbound cadences (automated emails, manual email tasks, phone call tasks, LinkedIn outreach tasks), sending schedules (`emailer_schedule`), and multi-mailbox rotation.")
